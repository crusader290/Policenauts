#!/usr/bin/env python3
"""Generate build.ninja for the Policenauts static recompilation.

Pipeline:
  1. extract   disc image -> extracted/ (ISO9660 + FRID .DPK unpack)
  2. recomp    extracted/ + recomp/segments.toml + config/symbol_addrs*.txt -> generated/*.c
  3. cc        generated/*.c + runtime/*.c -> build/policenauts.exe

Usage:
  python configure.py [--disc PATH_TO_DISC1.bin] [--cc gcc] [--opt -O2]
  ninja
"""
import argparse
import glob
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from ninja_syntax import Writer  # noqa: E402


def default_disc():
    hits = sorted(glob.glob(os.path.join(ROOT, "Policenauts PSX*", "*Disc 1*", "*.bin")))
    return hits[0] if hits else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--disc", default=default_disc(), help="Disc 1 .bin (MODE2/2352)")
    ap.add_argument("--cc", default="gcc")
    ap.add_argument("--opt", default="-O2")
    args = ap.parse_args()
    if not args.disc:
        sys.exit("disc image not found; pass --disc")

    py = sys.executable.replace("\\", "/")
    disc = os.path.relpath(args.disc, ROOT).replace("\\", "/")

    # Disc images for the runtime (Disc 2 is found next to Disc 1).
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    disc2 = sorted(glob.glob(os.path.join(ROOT, "Policenauts PSX*", "*Disc 2*", "*.bin")))
    with open(os.path.join(ROOT, "build", "discs.txt"), "w", newline="\n") as f:
        f.write(os.path.abspath(args.disc) + "\n")
        if disc2:
            f.write(os.path.abspath(disc2[0]) + "\n")

    w = Writer(open(os.path.join(ROOT, "build.ninja"), "w", newline="\n"))
    w.comment("generated by configure.py - do not edit")
    w.variable("ninja_required_version", "1.10")
    w.variable("python", py)
    w.variable("cc", args.cc)
    w.variable("cflags", f"-std=c11 {args.opt} -g -fno-strict-aliasing -fwrapv "
                         "-Iruntime -Igenerated -Wall -Wno-unused-label -Wno-unused-variable")
    w.variable("gen_cflags", f"-std=c11 {args.opt} -fno-strict-aliasing -fwrapv "
                             "-Iruntime -Igenerated -w")
    w.variable("ldflags", "-lgdi32 -luser32 -lwinmm")
    w.newline()

    w.rule("extract", "$python tools/extract_all.py \"$disc\" extracted",
           description="EXTRACT $in")
    w.rule("recomp", "$python recomp/recomp.py --out generated", description="RECOMP")
    w.rule("cc", "$cc $cflags -MMD -MF $out.d -c $in -o $out", deps="gcc", depfile="$out.d",
           description="CC $in")
    w.rule("cc_gen", "$cc $gen_cflags -MMD -MF $out.d -c $in -o $out", deps="gcc",
           depfile="$out.d", description="CC $in")
    w.rule("link", "$cc $in -o $out $ldflags", description="LINK $out")
    w.newline()

    stamp = "extracted/.stamp"
    w.build(stamp, "extract", disc, implicit=["tools/extract_all.py", "tools/psxiso.py",
                                                "tools/dpk.py"], variables={"disc": disc})

    # The generated file list is fixed by the segment config; recomp emits it.
    recomp_inputs = sorted(glob.glob("recomp/*.py") + glob.glob("recomp/*.toml") +
                           glob.glob("config/*.txt"))
    gen_list = os.path.join(ROOT, "generated", "sources.txt")
    gen_sources = []
    if os.path.exists(gen_list):
        gen_sources = [l.strip() for l in open(gen_list) if l.strip()]
    gen_c = [f"generated/{s}" for s in gen_sources]
    w.build(gen_c + ["generated/funcs.h"], "recomp", recomp_inputs, implicit=[stamp])

    objs = []
    for c in gen_c:
        o = "build/obj/" + os.path.basename(c)[:-2] + ".o"
        w.build(o, "cc_gen", c, order_only=["generated/funcs.h"])
        objs.append(o)
    for c in sorted(glob.glob("runtime/*.c")):
        c = c.replace("\\", "/")
        o = "build/obj/rt_" + os.path.basename(c)[:-2] + ".o"
        w.build(o, "cc", c, order_only=["generated/funcs.h"])
        objs.append(o)
    w.build("build/policenauts.exe", "link", objs)
    w.default("build/policenauts.exe")
    if not gen_sources:
        print("note: generated/sources.txt missing - run `python recomp/recomp.py` then re-run configure.py")
    print("wrote build.ninja")


if __name__ == "__main__":
    main()
